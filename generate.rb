#!/usr/bin/env ruby
# frozen_string_literal: true

# Renders palette.rb into the files that consume it. One method per output;
# add a terminal by adding a method and a line in OUTPUTS.
require_relative 'palette'

ROOT = __dir__

def lua_palette(p)
  lines = ['-- Generated by generate.rb from palette.rb. Do not edit; run `make generate`.', 'return {']
  p[:base].each { |k, v| lines << "  #{k} = \"#{v}\"," }
  %i[bright tint tint_dim mid].each do |set|
    lines << "  #{set} = {"
    p[set].each { |k, v| lines << "    #{k} = \"#{v}\"," }
    lines << '  },'
  end
  lines << '  -- ANSI 0-15'
  lines << '  term = {'
  p[:term].each_slice(4) { |row| lines << "    #{row.map { |v| "\"#{v}\"" }.join(', ')}," }
  lines << '  },'
  lines << '}'
  "#{lines.join("\n")}\n"
end

def ghostty(p)
  b = p[:base]
  lines = ['# holed. Generated by generate.rb from palette.rb. Do not edit.',
           '# Install: copy to ~/.config/ghostty/themes/holed and set `theme = holed`.']
  p[:term].each_with_index { |hex, i| lines << "palette = #{i}=#{hex}" }
  lines << "background = #{b[:black]}"
  lines << "foreground = #{b[:gray6]}"
  lines << "cursor-color = #{b[:gray6]}"
  lines << "cursor-text = #{b[:black]}"
  lines << "selection-background = #{b[:gray3]}"
  lines << "selection-foreground = #{b[:white]}"
  "#{lines.join("\n")}\n"
end

OUTPUTS = {
  'lua/holed/palette.lua' => method(:lua_palette),
  'extras/ghostty/holed' => method(:ghostty)
}.freeze

if __FILE__ == $PROGRAM_NAME
  p = palette
  OUTPUTS.each do |rel, renderer|
    path = File.join(ROOT, rel)
    Dir.mkdir(File.dirname(path)) unless Dir.exist?(File.dirname(path))
    File.write(path, renderer.call(p))
    puts "wrote #{rel}"
  end
end
